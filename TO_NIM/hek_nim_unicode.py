_SEQ_REPR_HELPER = """\
proc adascriptRepr[T](x: T): string =
  ## What Python's repr gives an element of a list: quotes on a string or a
  ## char, True and False, and the member's name for an enum.
  when T is string:
    let q = if '\\'' in x and '"' notin x: '"' else: '\\''
    result = $q
    for c in x:
      case c
      of '\\\\': result.add "\\\\\\\\"
      of '\\n': result.add "\\\\n"
      of '\\t': result.add "\\\\t"
      of '\\r': result.add "\\\\r"
      else:
        if c == q: result.add '\\\\'
        result.add c
    result.add q
  elif T is char: adascriptRepr($x)
  elif T is bool: (if x: "True" else: "False")
  else: $x

proc `$`(x: bool): string {.used.} =
  ## True and False, as Python prints them; system's says true and false.
  if x: "True" else: "False"

proc `$`[T: tuple](x: T): string {.used.} =
  ## A tuple prints as Python prints it: its strings quoted as repr quotes
  ## them, and a single one with its comma, `(1,)`.
  result = "("
  var n = 0
  for v in x.fields:
    if n > 0: result.add ", "
    result.add adascriptRepr(v)
    inc n
  if n == 1: result.add ","
  result.add ")"

proc `$`[T](xs: seq[T]): string {.used.} =
  ## A list prints as Python prints it -- `[1, 2]`, not Nim's `@[1, 2]`, with
  ## its elements as repr shows them.
  result = "["
  for i, x in xs:
    if i > 0: result.add ", "
    result.add adascriptRepr(x)
  result.add "]"\
"""


# Python's case changes on a whole string, Unicode-aware as Python's are:
# capitalize and title have no strutils counterpart (capitalizeAscii leaves
# the rest as it is), swapcase none at all. casefold is lower() here: the
# full case folding (German ß to ss) is not in std/unicode.
_CASE_HELPER = """\
proc adascriptCapitalize(s: string): string =
  var first = true
  for r in s.runes:
    result.add toUTF8(if first: toUpper(r) else: toLower(r))
    first = false

proc adascriptTitle(s: string): string =
  var inWord = false
  for r in s.runes:
    let cased = isAlpha(r)
    result.add toUTF8(if cased and not inWord: toUpper(r)
                      elif cased: toLower(r) else: r)
    inWord = cased

proc adascriptSwapcase(s: string): string =
  for r in s.runes:
    result.add toUTF8(if isUpper(r): toLower(r)
                      elif isLower(r): toUpper(r) else: r)

proc adascriptCasefold(s: string): string =
  for r in s.runes:
    result.add toUTF8(toLower(r))
"""


# A table prints as Python prints a dict: `{'k': 1}`, keys and values as repr
# shows them. Only for a program that has tables imported.
# An array prints as a list does: only for a program that has one.
_ARRAY_REPR_HELPER = """\
proc `$`[I, T](xs: array[I, T]): string {.used.} =
  ## An array prints as a list does, its values in index order -- an [E]T
  ## too, as Python prints it.
  result = "["
  var first = true
  for x in xs:
    if not first: result.add ", "
    first = false
    result.add adascriptRepr(x)
  result.add "]"
"""


